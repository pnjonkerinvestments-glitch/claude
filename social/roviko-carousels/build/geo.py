"""Build data/geo.js for the carousels: every country's outline in lon/lat.

  python3 build/geo.py  ->  data/geo.js  (window.GEO = {ISO3: [polygon[ring[[lon, lat], ...]]]}, window.GEO_EXTRA = [ring, ...])

* Countries: roviko.app's own boundaries (roviko/public/data/boundaries.json, Natural Earth via world-atlas).
* Land the app's roster doesn't cover (Greenland, Western Sahara, Taiwan, Antarctica, Kosovo, ...) comes from the
  launch film's 1:110m world map, so no land shows up as sea. Those features are never highlighted.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = ROOT.parent.parent
bounds = json.loads((REPO / 'roviko' / 'public' / 'data' / 'boundaries.json').read_text())
countries = json.loads((REPO / 'roviko' / 'public' / 'data' / 'countries.json').read_text())
roster = {c['numeric'] for c in countries}

geo = {k: [[[[round(x, 3), round(y, 3)] for x, y in ring] for ring in poly] for poly in g] for k, g in bounds.items()}

src = (REPO / 'social' / 'roviko-launch-film' / 'assets' / 'map.js').read_text()
extra = []
for m in re.finditer(r'\{"id":"([^"]*)","d":"([^"]+)"\}', src):
    cid, d = m.groups()
    if cid in roster:
        continue
    for part in re.split(r'[MZ]', d):
        pts = re.findall(r'(-?[\d.]+),(-?[\d.]+)', part)
        if len(pts) < 3:
            continue
        # equirectangular 1000x500 -> lon/lat
        extra.append([[round(float(u) / 1000 * 360 - 180, 3), round(90 - float(v) / 500 * 180, 3)] for u, v in pts])

out = ROOT / 'data' / 'geo.js'
out.parent.mkdir(exist_ok=True)
out.write_text('// generated by build/geo.py\nwindow.GEO = ' + json.dumps(geo, separators=(',', ':')) + ';\nwindow.GEO_EXTRA = ' + json.dumps(extra, separators=(',', ':')) + ';\n')
print(f'{len(geo)} countries, {len(extra)} extra rings -> {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)')
