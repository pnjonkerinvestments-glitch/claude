"""Bundle the numbers for the trend posts into data/trends.js (window.TR), read by roviko-shorts/trends.html.
  python3 social/roviko-trends/build_italy.py && python3 social/roviko-trends/build_data.py
Capitals: Natural Earth 10m populated places (Admin-0 capitals), matched to roviko.app's 195 countries (data/capitals.json)."""
import json, math
from pathlib import Path
H = Path(__file__).resolve().parent
CAP = json.loads((H / 'data/capitals.json').read_text()); IT = json.loads((H / 'data/italy.json').read_text())
xs = [v['lon'] for v in CAP.values()]; ys = [v['lat'] for v in CAP.values()]; n = len(xs); mx, my = sum(xs) / n, sum(ys) / n
sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys)); sxx = sum((x - mx) ** 2 for x in xs); syy = sum((y - my) ** 2 for y in ys)
b = sxy / sxx; a = my - b * mx; r = sxy / math.sqrt(sxx * syy)
TR = dict(caps=[[k, v['capital'], v['lon'], v['lat']] for k, v in CAP.items()], trend=dict(a=a, b=b, r=r, mlon=mx, mlat=my, n=n),
          italy=dict(all=IT['all'], no_micro=IT['no_micro'], grid=IT['grid']))
(H / 'data/trends.js').write_text('// generated by build_data.py\nwindow.TR = ' + json.dumps(TR, separators=(',', ':')) + ';\n')
print(n, 'capitals; trend lat = %.2f %+.4f*lon, r = %.3f; mean %.1fE %.1fN' % (a, b, r, mx, my))
